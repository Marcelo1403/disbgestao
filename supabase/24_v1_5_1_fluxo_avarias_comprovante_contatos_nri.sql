create or replace function public.refresh_damage_request_status(p_request_id uuid)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  v_total integer;
  v_pending integer;
  v_approved integer;
  v_rejected integer;
  v_launched integer;
  v_delivered integer;
  v_status text;
begin
  select count(*),
         count(*) filter(where status='PENDENTE'),
         count(*) filter(where status='APROVADO'),
         count(*) filter(where status='REPROVADO'),
         count(*) filter(where status='LANCADO'),
         count(*) filter(where status='ENTREGUE')
    into v_total,v_pending,v_approved,v_rejected,v_launched,v_delivered
  from public.damage_items
  where request_id=p_request_id;

  v_status := case
    when v_total=0 or v_pending=v_total then 'PENDENTE'
    when v_approved=v_total then 'APROVADO'
    when v_rejected=v_total then 'REPROVADO'
    when v_launched=v_total then 'LANCADO'
    when v_delivered=v_total then 'ENTREGUE'
    else 'PARCIAL'
  end;

  update public.damage_requests
     set status=v_status,
         last_review_at=case when v_pending=v_total then last_review_at else now() end
   where id=p_request_id;
end;
$$;

create or replace function public.review_damage_items(p_item_ids uuid[], p_status text, p_note text default '')
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_profile public.profiles%rowtype;
  v_req uuid;
  v_status text;
  v_note text;
  v_updated integer;
begin
  if not public.has_permission('DELIVERY_DAMAGE_REVIEW') then raise exception 'FORBIDDEN'; end if;
  v_status := upper(coalesce(p_status,''));
  if v_status not in ('APROVADO','REPROVADO') then raise exception 'STATUS_INVALIDO'; end if;
  v_note := btrim(coalesce(p_note,''));
  if v_note='' then raise exception 'JUSTIFICATIVA_OBRIGATORIA'; end if;

  select * into v_profile from public.profiles where id=auth.uid() and active=true;
  if v_profile.id is null then raise exception 'UNAUTHORIZED'; end if;

  update public.damage_items
     set status=v_status,
         reviewer_id=auth.uid(),
         reviewer_name=v_profile.name,
         reviewed_at=now(),
         review_note=v_note,
         launched_by=null,
         launched_by_name=null,
         launched_at=null,
         delivered_by=null,
         delivered_by_name=null,
         delivered_at=null
   where id=any(p_item_ids)
     and status='PENDENTE';

  get diagnostics v_updated=row_count;
  if v_updated=0 then raise exception 'NENHUM_ITEM_PENDENTE'; end if;

  for v_req in select distinct request_id from public.damage_items where id=any(p_item_ids) loop
    perform public.refresh_damage_request_status(v_req);
  end loop;

  return jsonb_build_object('ok',true,'updated',v_updated,'status',v_status);
end;
$$;

