create or replace function public.discard_nri_pending(p_source_type text,p_source_id uuid,p_reason text default '')
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_profile public.profiles%rowtype;
  v_source text := upper(btrim(coalesce(p_source_type,'')));
  v_updated integer;
begin
  if not public.has_permission('NRI_CREATE') then raise exception 'FORBIDDEN'; end if;
  select * into v_profile from public.profiles where id=auth.uid() and active=true;
  if v_profile.id is null then raise exception 'UNAUTHORIZED'; end if;

  if v_source='PULL' then
    update public.pull_trips
       set nri_status='DISCARDED',
           nri_discarded_at=now(),
           nri_discarded_by=auth.uid(),
           nri_discarded_by_name=v_profile.name,
           nri_discard_reason=btrim(coalesce(p_reason,''))
     where id=p_source_id
       and cycle_type='PULL'
       and status='ARRIVED'
       and nri_status='PENDING';
    get diagnostics v_updated=row_count;
  elsif v_source='MARKETPLACE' then
    update public.marketplace_receipts
       set nri_status='DISCARDED',
           status='COMPLETED',
           nri_discarded_at=now(),
           nri_discarded_by=auth.uid(),
           nri_discarded_by_name=v_profile.name,
           nri_discard_reason=btrim(coalesce(p_reason,'')),
           updated_at=now()
     where id=p_source_id
       and status='PENDING_NRI'
       and nri_status='PENDING';
    get diagnostics v_updated=row_count;
  else
    raise exception 'TIPO_ORIGEM_INVALIDO';
  end if;

  if coalesce(v_updated,0)=0 then raise exception 'PENDENCIA_NRI_NAO_ENCONTRADA'; end if;
  return jsonb_build_object('ok',true,'source',v_source,'id',p_source_id,'nri_status','DISCARDED');
end;
$$;

