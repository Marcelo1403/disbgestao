create or replace function public.normalize_customer_phone(p_phone text)
returns text
language plpgsql
immutable
as $$
declare v_phone text;
begin
  v_phone := regexp_replace(coalesce(p_phone,''), E'\\D','','g');
  if left(v_phone,2)='00' then v_phone:=substr(v_phone,3); end if;
  if length(v_phone) in (10,11) then v_phone:='55'||v_phone; end if;
  if v_phone !~ '^55[0-9]{10,11}$' then return ''; end if;
  return v_phone;
end;
$$;

create or replace function public.save_customer_contact(
  p_customer_id uuid,
  p_customer_code text,
  p_phone text,
  p_label text default ''
)
returns uuid
language plpgsql
security definer
set search_path=public
as $$
declare
  v_profile public.profiles%rowtype;
  v_customer public.customers%rowtype;
  v_phone text;
  v_source text;
  v_id uuid;
  v_code text := regexp_replace(coalesce(p_customer_code,''), E'\\D','','g');
begin
  if not (public.has_permission('ADMIN_BASES') or public.has_permission('DELIVERY_DAMAGE_CREATE')) then raise exception 'FORBIDDEN'; end if;
  select * into v_profile from public.profiles where id=auth.uid() and active=true;
  if v_profile.id is null then raise exception 'UNAUTHORIZED'; end if;

  v_phone := public.normalize_customer_phone(p_phone);
  if v_phone='' then raise exception 'TELEFONE_INVALIDO'; end if;

  if p_customer_id is not null then
    select * into v_customer from public.customers where id=p_customer_id limit 1;
  end if;
  if v_customer.id is null and v_code<>'' then
    select * into v_customer
    from public.customers
    where ltrim(regexp_replace(code,E'\\D','','g'),'0')=ltrim(v_code,'0')
    order by branch,code
    limit 1;
  end if;
  if v_customer.id is null then raise exception 'CLIENTE_NAO_ENCONTRADO'; end if;

  v_source := case when public.has_permission('ADMIN_BASES') then 'ADMIN' else 'MOTORISTA' end;

  insert into public.customer_contacts(
    customer_id,customer_code,phone_normalized,label,source,created_by,updated_by,updated_by_name,updated_at
  ) values(
    v_customer.id,regexp_replace(v_customer.code,E'\\D','','g'),v_phone,btrim(coalesce(p_label,'')),v_source,
    auth.uid(),auth.uid(),v_profile.name,now()
  )
  on conflict(customer_id,phone_normalized) do update set
    customer_code=excluded.customer_code,
    label=case when btrim(excluded.label)<>'' then excluded.label else public.customer_contacts.label end,
    source=excluded.source,
    updated_by=excluded.updated_by,
    updated_by_name=excluded.updated_by_name,
    updated_at=now()
  returning id into v_id;

  return v_id;
end;
$$;

